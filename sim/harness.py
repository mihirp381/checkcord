async def up() -> None:
    problems = preflight()
    if problems:
        raise SystemExit("cannot start:\n  " + "\n  ".join(problems))
    started = time.time()
    s = {
        "slack_client_id": f"{secrets.randbelow(10**10)}.{secrets.randbelow(10**12)}",
        "slack_client_secret": token(n=32),
        "slack_signing_secret": token(n=32),
        "slack_app_token": "xapp-1-" + token(n=40),
        "github_token": "ghp_" + token(n=36),
        "jira_token": token(n=24),
        "oidc_client_id": "checkcord-sim",
        "oidc_client_secret": token(n=32),
        "notion_client_id": "notion-" + token(n=12),
        "notion_client_secret": "secret_" + token(n=32),
        "linear_client_id": "lin-" + token(n=16),
        "linear_client_secret": token(n=32),
        "teams_client_id": str(uuid.uuid4()),
        "teams_client_secret": token(n=34),
    }
    state: dict[str, Any] = {**s, "runs": 0, "started": now_iso()}
    state["world_pid"] = start_world(s)
    overrides = env_overrides(s)
    write_env(overrides)
    state["overrides"] = overrides
    save_state(state)
    print("Building and starting the stack (this takes a while the first time)...", flush=True)
    res = await asyncio.to_thread(compose, "up", "-d", "--build", "--wait", timeout=3600)
    if res.code != 0:
        raise SystemExit(f"docker compose up failed:\n{res.text[-3000:]}")
    doctor = await cli("doctor")
    state["doctor"] = doctor.text
    init = await cli("init")
    admin_key = secret_after("Created admin API key", init.out)
    if init.code != 0 or not admin_key:
        raise SystemExit(f"checkcord init failed:\n{init.text}")
    state["admin_key"] = admin_key
    save_state(state)

    calls = Calls()
    async with httpx.AsyncClient(timeout=120) as http:
        admin = Admin(http, calls, admin_key)
        world = WorldClient(world_port())
        scim = await admin.post("/api/v1/admin/keys", {"name": "sim-scim", "admin": True})
        if not scim.ok:
            raise SystemExit(f"SCIM key: {scim.status} {scim.text}")
        state["scim_key"] = scim.body["key"]
        scim_admin = Admin(http, calls, state["scim_key"], who="scim")
        await world.call(
            "/idp/groups",
            **{p.email: [company.ADMIN_GROUP] if p.admin else ["staff"] for p in company.PEOPLE},
        )
        people: dict[str, Any] = {}
        for p in company.PEOPLE:
            r = await scim_admin.scim("POST", "/Users", scim_user(p, p.style))
            if r.status != 201:
                raise SystemExit(f"SCIM create {p.email}: {r.status} {r.text}")
            k = await admin.post(
                "/api/v1/admin/keys",
                {"name": f"sim-{p.key}", "admin": False, "user_email": p.email},
            )
            if not k.ok:
                raise SystemExit(f"key for {p.email}: {k.status} {k.text}")
            people[p.key] = {
                "email": p.email,
                "scim_id": r.body["id"],
                "key": k.body["key"],
                "key_id": k.body["id"],
            }
        users = await admin.get("/api/v1/admin/users", limit=100)
        for u in users.body.get("items", []):
            for v in people.values():
                if v["email"] == u["email"]:
                    v["user_id"] = u["id"]
        state["people"] = people
        state["groups"] = {}
        for name, members in GROUPS.items():
            g = await scim_admin.scim(
                "POST",
                "/Groups",
                {
                    "schemas": ["urn:ietf:params:scim:schemas:core:2.0:Group"],
                    "displayName": name,
                    "members": [{"value": people[k]["scim_id"]} for k in members],
                },
            )
            if g.status != 201:
                raise SystemExit(f"SCIM group {name}: {g.status} {g.text}")
            state["groups"][name] = g.body["id"]
        save_state(state)

        state["slack_install"] = await install_slack(admin, calls)
        state["connect"] = []
        for repo in (company.WEB_APP, company.HANDBOOK):
            state["connect"].append(await connect_github(admin, world, state, repo))
        state["account_import"] = await import_accounts()
        save_state(state)
        await world.close()

    sec = Secrets()
    for v in _secret_values(state):
        sec.add(v)
    run = await Run.open(state, None)
    try:
        ok, seconds, left = await run.settle(900)
        state["bring_up_settle"] = {"ok": ok, "seconds": seconds, "open": left}
        health = await run.world.get("/health")
        state["slack_socket"] = health
        if not health.get("slack_connected"):
            print("warning: Checkcord has no Socket Mode connection to the Slack stand-in")
    finally:
        await run.close()
    state["bring_up_seconds"] = round(time.time() - started, 1)
    save_state(state)
    print(sec.mask(f"Up in {state['bring_up_seconds']} s. Doctor:\n{doctor.text}"))


def down() -> None:
    if ENV.exists() and ENV.read_text().splitlines()[:1] != [ENV_MARK]:
        raise SystemExit(".env was not written by sim; leaving it and the stack alone")
    res = compose("down", "-v", "--remove-orphans", timeout=600)
    print(res.text.strip()[-2000:])
    stop_world()
    if ENV.exists():
        ENV.unlink()
    if STATE.exists():
        STATE.unlink()
    for name in ("admin.key",):
        (OUT / name).unlink(missing_ok=True)
    print("Stack down with volumes removed, world stopped, .env deleted.")


def _secret_values(state: dict[str, Any]) -> Iterable[str]:
    for k in (
        "slack_client_secret",
        "slack_signing_secret",
        "slack_app_token",
        "github_token",
        "jira_token",
        "oidc_client_secret",
        "notion_client_secret",
        "linear_client_secret",
        "teams_client_secret",
        "admin_key",
        "scim_key",
        "jira_webhook_secret",
        "signed_secret",
    ):
        if state.get(k):
            yield state[k]
    yield from state.get("webhook_secrets", {}).values()
    for p in state.get("people", {}).values():
        yield p["key"]
    yield from state.get("extra_secrets", [])


