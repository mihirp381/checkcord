def stop_world() -> None:
    pid_file = OUT / "world.pid"
    if not pid_file.exists():
        return
    pid = int(pid_file.read_text())
    try:
        os.killpg(pid, signal.SIGTERM)
    except ProcessLookupError:
        pass
    for _ in range(30):
        try:
            os.kill(pid, 0)
        except ProcessLookupError:
            break
        time.sleep(0.2)
    else:
        try:
            os.killpg(pid, signal.SIGKILL)
        except ProcessLookupError:
            pass
    pid_file.unlink()
    for _ in range(50):
        if _port_free(world_port()):
            break
        time.sleep(0.2)


def secret_after(label: str, text: str) -> str | None:
    lines = text.splitlines()
    for i, line in enumerate(lines):
        if line.startswith(label):
            for nxt in lines[i + 1 :]:
                if nxt.strip():
                    return nxt.strip()
    return None


def url_after(label: str, text: str) -> str | None:
    m = re.search(rf"{re.escape(label)}\s+(\S+)", text)
    return m.group(1) if m else None


async def connect_github(
    admin: Admin, world: WorldClient, state: dict[str, Any], repo: str
) -> dict[str, Any]:
    res = await cli(
        "connect", "github", "--repo", repo, env={"CHECKCORD_GITHUB_TOKEN": state["github_token"]}
    )
    secret = secret_after("Webhook secret", res.out)
    url = url_after("Payload URL:", res.out)
    if res.code != 0 or not secret or not url:
        raise RuntimeError(f"connect github {repo} failed ({res.code}): {res.text[-800:]}")
    await world.call("/github/register", repo=repo, url=url, secret=secret)
    state.setdefault("webhook_secrets", {})[repo] = secret
    return {"repo": repo, "exit": res.code, "output": res.out}


async def install_slack(admin: Admin, calls: Calls, provider: str = "slack") -> dict[str, Any]:
    link = await admin.post("/api/v1/admin/connections/install-link", {"provider": provider})
    if not link.ok:
        raise RuntimeError(f"install link: {link.status} {link.text[:300]}")
    steps = []
    jar: dict[str, str] = {}
    async with httpx.AsyncClient(timeout=60, follow_redirects=False) as browser:
        url = link.body["url"]
        for _ in range(8):
            target = to_host(url, world_port())
            # A browser sends Secure cookies to http://localhost; httpx's jar does not.
            same = target.startswith(API)
            headers = {"Cookie": "; ".join(f"{k}={v}" for k, v in jar.items())} if same else {}
            r = await browser.get(target, headers=headers)
            browser.cookies.clear()
            if same:
                for raw in r.headers.get_list("set-cookie"):
                    name, _, rest = raw.partition("=")
                    jar[name.strip()] = rest.split(";", 1)[0]
            steps.append({"url": url.split("?")[0], "status": r.status_code})
            calls.add("operator browser", "GET", url.split("?")[0], r.status_code)
            nxt = r.headers.get("location")
            if not nxt and r.status_code == 200 and "oauth/v2/authorize" in r.text:
                m = re.search(r'href="([^"]*oauth/v2/authorize[^"]*)"', r.text)
                nxt = m.group(1).replace("&amp;", "&") if m else None
            if not nxt:
                return {"steps": steps, "final_status": r.status_code, "final": r.text[:300]}
            url = str(httpx.URL(url).join(nxt))
    return {"steps": steps, "final_status": None}


