_LINE = re.compile(r"^([a-zA-Z_:][a-zA-Z0-9_:]*)(\{([^}]*)\})?\s+(\S+)")


def parse_metrics(text: str) -> list[tuple[str, dict[str, str], float]]:
    rows = []
    for line in text.splitlines():
        if not line or line.startswith("#"):
            continue
        m = _LINE.match(line)
        if not m:
            continue
        labels = dict(re.findall(r'(\w+)="((?:[^"\\]|\\.)*)"', m.group(3) or ""))
        try:
            rows.append((m.group(1), labels, float(m.group(4))))
        except ValueError:
            continue
    return rows


def open_items(text: str) -> dict[str, float]:
    found = {}
    for name, labels, value in parse_metrics(text):
        if name in OPEN_GAUGES and value != 0:
            label = ",".join(f"{k}={v}" for k, v in sorted(labels.items()))
            found[f"{name}{{{label}}}"] = value
    return found


