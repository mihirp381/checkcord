# Helpers for checks


def _strings(value: Any) -> list[str]:
    if isinstance(value, str):
        if value[:1] in "{[":
            try:
                return _strings(json.loads(value))
            except ValueError:
                pass
        return [value]
    if isinstance(value, dict):
        return [s for v in value.values() for s in _strings(v)]
    if isinstance(value, list | tuple):
        return [s for v in value for s in _strings(v)]
    return [] if value is None else [str(value)]


def norm(value: Any) -> str:
    text = "\n".join(_strings(value))
    return " ".join(re.sub(r"[^0-9a-z]+", " ", text.lower()).split())


def snippet(text: str | None, words: int = 8) -> str:
    return " ".join(norm(text or "").split()[:words])


UUID = re.compile(r"[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}")


def middle(text: str | None, words: int = 8) -> str:
    found = norm(text or "").split()
    at = max(0, (len(found) - words) // 2)
    return " ".join(found[at : at + words])


def hit(body: Any, record_id: str | None, text: str | None = None) -> bool:
    """Whether a response carries the record: by id when the response has ids, else by text."""
    raw = body if isinstance(body, str) else json.dumps(body, default=str, ensure_ascii=False)
    if record_id and (record_id in raw or UUID.search(raw)):
        return record_id in raw
    s = middle(text)
    return bool(s) and s in norm(body)


def cli_counts(text: str) -> dict[str, int]:
    found = re.findall(r"^\s+([a-z][a-z ]+):\s+(\d+)\s*$", text, re.M)
    return {k.strip().replace(" ", "_"): int(v) for k, v in found}


def doctor_lines(text: str) -> dict[str, list[str]]:
    out: dict[str, list[str]] = {}
    for line in text.splitlines():
        head = line.strip().split(" ", 1)[0]
        if head.isupper() and len(head) >= 2:
            out.setdefault(head, []).append(line.strip())
    return out


def signed_headers(secret: str, body: bytes, at: float | None = None) -> dict[str, str]:
    import hashlib
    import hmac

    ts = str(int(at if at is not None else time.time()))
    mac = hmac.new(secret.encode(), ts.encode() + b"." + body, hashlib.sha256).hexdigest()
    return {
        "Content-Type": "application/json",
        "X-Checkcord-Timestamp": ts,
        "X-Checkcord-Signature": f"sha256={mac}",
    }
