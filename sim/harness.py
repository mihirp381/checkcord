class Secrets:
    def __init__(self) -> None:
        self.values: set[str] = set()

    def add(self, *values: str | None) -> None:
        for v in values:
            if v and len(v) >= 8:
                self.values.add(v)

    def mask(self, value: Any) -> Any:
        if isinstance(value, str):
            for s in sorted(self.values, key=len, reverse=True):
                if s in value:
                    value = value.replace(s, f"<secret:{len(s)}>")
            return value
        if isinstance(value, dict):
            return {self.mask(k): self.mask(v) for k, v in value.items()}
        if isinstance(value, list | tuple):
            return [self.mask(v) for v in value]
        return value


