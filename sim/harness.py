def _port_free(port: int) -> bool:
    with socket.socket() as s:
        s.settimeout(0.5)
        if s.connect_ex(("127.0.0.1", port)) == 0:
            return False
    with socket.socket() as s:
        s.setsockopt(socket.SOL_SOCKET, socket.SO_REUSEADDR, 1)
        try:
            s.bind(("127.0.0.1", port))
        except OSError:
            return False
    return True


def preflight() -> list[str]:
    problems = []
    if ENV.exists():
        first = ENV.read_text().splitlines()[:1]
        if first != [ENV_MARK]:
            problems.append(".env exists and was not written by sim; move it away first")
    if (
        compose("version").code != 0
        or subprocess.run(["docker", "info"], capture_output=True).returncode
    ):
        problems.append("Docker is not running")
    try:
        tags = httpx.get(OLLAMA + "/api/tags", timeout=5).json()
        have = {m["name"] for m in tags.get("models", [])}
        for model in MODELS:
            if model not in have and f"{model}:latest" not in have:
                problems.append(f"Ollama lacks {model}: ollama pull {model}")
    except httpx.HTTPError:
        problems.append("Ollama is not reachable on localhost:11434")
    for port in (API_PORT, WEB_PORT, world_port()):
        if not _port_free(port):
            problems.append(f"port {port} is taken")
    return problems


