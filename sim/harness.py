def write_env(overrides: dict[str, str]) -> None:
    base = (ROOT / ".env.local-models.example").read_text().splitlines()
    keys = set(overrides)
    lines = [ENV_MARK]
    for line in base:
        name = line.split("=", 1)[0].strip()
        if not line.startswith("#") and "=" in line and name in keys:
            continue
        lines.append(line)
    lines.append("")
    lines.append("# simulation overrides")
    lines += [f"{k}={v}" for k, v in overrides.items()]
    ENV.write_text("\n".join(lines) + "\n")
    ENV.chmod(0o600)


def save_state(state: dict[str, Any]) -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    STATE.write_text(json.dumps(state, indent=2))
    STATE.chmod(0o600)


